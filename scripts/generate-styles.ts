/**
 * Generates `packages/ui/src/style/utilities.css`: one class per token or spacing step a primitive's props can name
 * (`<Flex gap={2} radius="card" background="surface">` is `hs-d-flex hs-gap-2 hs-r-card hs-bg-surface`), so drawing a
 * primitive is joining a few strings, not working out and registering styles. Values are custom properties
 * (`--hs-surface`, `--hs-unit`, ...) written by `HashsomeProvider`, which is how a theme, a density or a project's
 * overrides reach every class without drawing anything again. Run via `pnpm generate:styles`; CI fails if the output would
 * change.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  NEGATIVE_SPACING_UNITS,
  PALETTE_KEYS,
  RADIUS_KEYS,
  SHADOW_KEYS,
  SPACING_PROPS,
  SPACING_UNITS,
  TYPOGRAPHY_KEYS,
  Z_INDEX_KEYS,
  kebab,
  unitSuffix,
} from '../packages/ui/src/style/names.ts';
import { formatWithRepoConfig } from './format.ts';

const OUT_FILE = join(import.meta.dirname, '..', 'packages', 'ui', 'src', 'style', 'utilities.css');
const TYPE_FILE = join(import.meta.dirname, '..', 'packages', 'ui', 'src', 'style', 'type.module.css');

const rules: string[] = [];
const rule = (selector: string, declarations: string) =>
  rules.push(`.hs-${selector} { ${declarations} }`);

// Spacing: a number of the spacing unit (a third of a space, so it follows density).
for (const [prop, properties] of Object.entries(SPACING_PROPS)) {
  const negatives = prop.startsWith('m') ? NEGATIVE_SPACING_UNITS : [];
  for (const units of [...SPACING_UNITS, ...negatives]) {
    rule(
      `${prop}-${unitSuffix(units)}`,
      properties.map((property) => `${property}: calc(var(--hs-unit) * ${units});`).join(' '),
    );
  }
}

rule('m-auto', 'margin: auto;');
rule('mt-auto', 'margin-top: auto;');
rule('ml-auto', 'margin-left: auto;');

// Layout.
for (const display of ['flex', 'inline-flex', 'grid']) {
  rule(`d-${display}`, `display: ${display};`);
}

for (const direction of ['row', 'column', 'row-reverse', 'column-reverse']) {
  rule(`fd-${direction}`, `flex-direction: ${direction};`);
}

for (const value of ['center', 'flex-start', 'flex-end', 'baseline', 'stretch']) {
  rule(`ai-${value}`, `align-items: ${value};`);
}

for (const value of [
  'center',
  'flex-start',
  'flex-end',
  'space-between',
  'space-around',
  'space-evenly',
]) {
  rule(`jc-${value}`, `justify-content: ${value};`);
}

rule('grow-0', 'flex-grow: 0;');
rule('grow-1', 'flex-grow: 1;');
rule('minw-0', 'min-width: 0;');
rule('minh-0', 'min-height: 0;');

for (const value of ['relative', 'absolute', 'fixed', 'sticky', 'static']) {
  rule(`pos-${value}`, `position: ${value};`);
}

for (const value of ['hidden', 'auto', 'visible', 'scroll', 'clip']) {
  rule(`ov-${value}`, `overflow: ${value};`);
}

for (const value of ['pointer', 'default', 'grab', 'progress', 'inherit', 'not-allowed']) {
  rule(`cur-${value}`, `cursor: ${value};`);
}

// What a press makes of an element that has an `onClick`.
rule('clickable', 'cursor: pointer; user-select: none;');

// Text.
for (const value of ['left', 'center', 'right', 'justify']) {
  rule(`ta-${value}`, `text-align: ${value};`);
}

rule('nowrap', 'white-space: nowrap;');
rule('upper', 'text-transform: uppercase;');
rule('to-ellipsis', 'text-overflow: ellipsis;');
rule('to-clip', 'text-overflow: clip;');

// Tokens.
for (const key of PALETTE_KEYS) {
  rule(`c-${kebab(key)}`, `color: var(--hs-${kebab(key)});`);
  rule(`bg-${kebab(key)}`, `background: var(--hs-${kebab(key)});`);
  for (const [side, property] of [
    ['', 'border'],
    ['t', 'border-top'],
    ['r', 'border-right'],
    ['b', 'border-bottom'],
    ['l', 'border-left'],
  ]) {
    rule(
      `bd${side}-${kebab(key)}`,
      `${property}: var(--hs-border-width) solid var(--hs-${kebab(key)});`,
    );
  }
}

rule('c-transparent', 'color: transparent;');
rule('bg-transparent', 'background: transparent;');

for (const key of RADIUS_KEYS) {
  rule(`r-${kebab(key)}`, `border-radius: var(--hs-radius-${kebab(key)});`);
}

for (const key of SHADOW_KEYS) {
  rule(`sh-${kebab(key)}`, `box-shadow: var(--hs-shadow-${kebab(key)});`);
}

for (const key of Z_INDEX_KEYS) {
  rule(`z-${kebab(key)}`, `z-index: var(--hs-z-${kebab(key)});`);
}

for (const key of TYPOGRAPHY_KEYS) {
  const name = kebab(key);
  rule(
    `t-${name}`,
    [
      'font-family: var(--hs-font-family);',
      `font-size: var(--hs-t-${name}-size);`,
      `font-weight: var(--hs-t-${name}-weight);`,
      `line-height: var(--hs-t-${name}-line);`,
      `letter-spacing: var(--hs-t-${name}-spacing);`,
    ].join(' '),
  );
}

const raw = `/* Generated by \`pnpm generate:styles\` from \`scripts/generate-styles.ts\`. Do not edit by hand. */

/* Utilities sit above the base styles, and below every rule a component or a project writes (unlayered CSS beats a layer). */
@layer hs-base, hs-utilities;

@layer hs-utilities {
${rules.map((line) => `  ${line}`).join('\n')}
}
`;

writeFileSync(OUT_FILE, await formatWithRepoConfig(OUT_FILE, raw));

// The type scale as classes a component styles itself with (`composes: label from '../style/type.module.css'`).
const typeRaw = `/* Generated by \`pnpm generate:styles\` from \`scripts/generate-styles.ts\`. Do not edit by hand. */

${TYPOGRAPHY_KEYS.map((key) => {
  const name = kebab(key);
  return `.${key} {
  font-family: var(--hs-font-family);
  font-size: var(--hs-t-${name}-size);
  font-weight: var(--hs-t-${name}-weight);
  line-height: var(--hs-t-${name}-line);
  letter-spacing: var(--hs-t-${name}-spacing);
}`;
}).join('\n\n')}
`;

writeFileSync(TYPE_FILE, await formatWithRepoConfig(TYPE_FILE, typeRaw));
console.log(`Wrote ${OUT_FILE} (${rules.length} classes)`);
