/**
 * Generates `packages/ui/src/style/type.module.css`: one class per variant of the type scale, written in terms of the theme's
 * custom properties (`--hs-t-label-size`, ...), which a component's own stylesheet takes with
 * `composes: label from '../style/type.module.css'`. Run via `pnpm generate:styles`; CI fails if the output would change.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { TYPOGRAPHY_KEYS, kebab } from '../packages/ui/src/style/names.ts';
import { formatWithRepoConfig } from './format.ts';

const TYPE_FILE = join(
  import.meta.dirname,
  '..',
  'packages',
  'ui',
  'src',
  'style',
  'type.module.css',
);

// The type scale as classes a component styles itself with (`composes: label from '../style/type.module.css'`).
const typeRaw = `/* Generated by \`pnpm generate:styles\` from \`scripts/generate-styles.ts\`. Do not edit by hand. */

${TYPOGRAPHY_KEYS.map((key) => {
  const name = kebab(key);
  return `.${key} {
  font-family: var(--hs-font-family);
  font-size: var(--hs-t-${name}-size);
  font-weight: var(--hs-t-${name}-weight);
  line-height: var(--hs-t-${name}-line);
  letter-spacing: var(--hs-t-${name}-spacing);
}`;
}).join('\n\n')}
`;

writeFileSync(TYPE_FILE, await formatWithRepoConfig(TYPE_FILE, typeRaw));
console.log(`Wrote ${TYPE_FILE}`);
