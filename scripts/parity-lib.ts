import type { CatalogName } from './ui-catalog-lib.ts';

export type ParityFile = Record<string, string>;

const FIXED = new Set(['native', 'planned', 'web-only']);

/** Why a status string is malformed, or `undefined` when it is one of the allowed forms. */
export function statusProblem(status: unknown): string | undefined {
  if (typeof status !== 'string') {
    return 'status must be a string';
  }

  if (FIXED.has(status) || /^planned#\d+$/.test(status) || /^native:[A-Za-z_]\w*$/.test(status)) {
    return undefined;
  }

  if (status.startsWith('native-only:')) {
    return status.slice('native-only:'.length).trim() ? undefined : 'native-only needs a reason';
  }

  return `unknown status "${status}" (use native, planned, planned#<issue>, web-only, native:<KotlinName> or native-only:<reason>)`;
}

/** Everything wrong with `parity` against the names the catalog exports. Native-only entries name no web export, so they are not "stale". */
export function parityProblems(names: CatalogName[], parity: ParityFile): string[] {
  const known = new Set(names.map((entry) => entry.name));
  const problems: string[] = [];

  for (const { name } of names) {
    if (!(name in parity)) {
      problems.push(
        `missing: ${name} is exported by @hashsome/ui but has no entry in android/parity.json`,
      );
    }
  }

  for (const [name, status] of Object.entries(parity)) {
    if (!known.has(name) && !String(status).startsWith('native-only:')) {
      problems.push(
        `stale: ${name} is in android/parity.json but no longer exported by @hashsome/ui`,
      );
    }

    const problem = statusProblem(status);
    if (problem) {
      problems.push(`malformed: ${name}: ${problem}`);
    }
  }

  return problems;
}

/** How a status reads in the table: the status word, and the native type or notes. */
export function describeStatus(status: string): { status: string; notes: string } {
  if (status.startsWith('native:')) {
    return { status: 'native', notes: `\`${status.slice('native:'.length)}\`` };
  }

  if (status.startsWith('native-only:')) {
    return { status: 'native-only', notes: status.slice('native-only:'.length).trim() };
  }

  if (status.startsWith('planned#')) {
    return { status: 'planned', notes: `#${status.slice('planned#'.length)}` };
  }

  return { status, notes: '' };
}

const GROUPS: [string, (entry: CatalogName) => boolean][] = [
  [
    'Entity components',
    (entry) => entry.kind === 'component' && entry.group === 'Entity components',
  ],
  ['Layout', (entry) => entry.kind === 'component' && entry.group !== 'Entity components'],
  ['Hooks', (entry) => entry.kind === 'hook'],
];

/** The markdown for `android/PARITY.md`. */
export function renderParity(names: CatalogName[], parity: ParityFile): string {
  const lines = [
    '# Android parity with `@hashsome/ui`',
    '',
    '_Generated by `pnpm generate:parity` from `android/parity.json` and the exports of `packages/ui`. Do not edit by hand: change `android/parity.json`, then regenerate. CI fails if this file drifts._',
    '',
    'Statuses: `native` (a Kotlin counterpart exists; `native:<Name>` when it is named differently), `planned` (`planned#<issue>` when tracked), `web-only` (no native counterpart by design), `native-only` (exists only on Android, with the reason).',
    '',
  ];

  for (const [heading, belongs] of GROUPS) {
    const rows = names.filter(belongs);
    if (rows.length === 0) {
      continue;
    }

    lines.push(
      `## ${heading}`,
      '',
      '| Web | Kind | Status | Native type / notes |',
      '|---|---|---|---|',
    );

    for (const { name, kind } of rows) {
      const { status, notes } = describeStatus(parity[name] ?? 'missing');
      lines.push(`| \`${name}\` | ${kind} | ${status} | ${notes} |`);
    }

    lines.push('');
  }

  const nativeOnly = Object.entries(parity).filter(
    ([name, status]) =>
      status.startsWith('native-only:') && !names.some((entry) => entry.name === name),
  );

  if (nativeOnly.length > 0) {
    lines.push('## Native only', '', '| Native | Reason |', '|---|---|');
    for (const [name, status] of nativeOnly) {
      lines.push(`| \`${name}\` | ${describeStatus(status).notes} |`);
    }

    lines.push('');
  }

  return lines.join('\n').trimEnd() + '\n';
}
